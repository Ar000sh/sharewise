package de.hsh.favs.sharewise.shared;

/**
 * Stable error codes of the API contract (docs/api/openapi.yaml) with their HTTP status.
 */
public enum ErrorCode {

	BAD_REQUEST(400), UNAUTHENTICATED(401), NOT_A_MEMBER(403), GROUP_NOT_FOUND(404), INVITATION_NOT_FOUND(404),
	ALREADY_MEMBER(409), INVITATION_EXPIRED(410), AMOUNT_NOT_POSITIVE(422), PAYER_NOT_IN_GROUP(422),
	PARTICIPANT_NOT_IN_GROUP(422), NO_PARTICIPANTS(422), GROUP_NOT_OPEN(422), SPLIT_NOT_SUPPORTED(422),
	PAYMENT_EXCEEDS_OPEN_DEBT(422), SETTLEMENT_PAYMENT_NOT_FOUND(404), PAYMENT_NOT_PENDING(409), NOT_THE_CREDITOR(403),
	ACCOUNT_NOT_FOUND(404), ALREADY_INVITED(409), NOTIFICATION_NOT_FOUND(404), NOT_AN_ADMIN(403), MEMBER_NOT_FOUND(404),
	ALREADY_ADMIN(409);

	private final int status;

	ErrorCode(int status) {
		this.status = status;
	}

	public int status() {
		return status;
	}

}
